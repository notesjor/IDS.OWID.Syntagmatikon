    <h1>Satellitenfelder</h1>
    <p>Als Satelliten werden nach bestimmten inhaltlichen Kriterien
        zusammengefasste Felder von <a
            href="http://uwv.ids-mannheim.de/prepcon/infotexte/info.html#kookkurrenzprofile"><u>Partnerwörtern</u></a> bezeichnet.
        In „PREPCON<sup>online</sup>kontrastiv“ findet man für die
        Ausgangssprache Deutsch und die Kontrastsprachen Spanisch und Slowakisch
        verbale Satellitenfelder unabhängig von Gebrauchsaspekten. Darüber
        hinaus werden typische Partnerwörter für die einzelnen Gebrauchsaspekte
        in Feldern zusammengefasst. Diese sind in der Regel nach Wortarten
        unterteilt. Es gibt aber auch Fälle, in denen keine
        Wortartenunterscheidung vorgenommen wurde.</p>
    <p>Zu allen Satellitenfeldern können zum besseren Verständnis KWICs
        abgerufen werden.</p><br/>
    <h3>Beispiel</h3>
    <p>Für den Gebrauchsaspekt ‚wiederholbare Handlungen‘ bilden folgende
        Verb-Satelliten ein Feld: <em>schalten und walten</em>/<em>ein- und
            ausschalten</em>/<em>drehen und wenden</em>/<em>ändern und
            löschen</em>/…</p>
    <p>Für den Gebrauchsaspekt ‚Kochrezepte‘ bilden folgende Satelliten je
        ein Feld: Verben
        wie <em>würzen</em>/<em>garnieren</em>/<em>bestreuen</em>/<em>abschmecken</em>;
        Substantive
        wie <em>Pfeffer</em>/<em>Salz</em>/<em>Zucker</em>/<em>Rahm</em>/<em>Parmesan/</em>…</p>
    <p>Für den Gebrauchsaspekt ‚Überlegenheit im Sport‘ bilden folgende
        Satelliten je ein Feld: Verben
